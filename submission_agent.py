class GameObservation:
    """Parsed game state from the official engine's obs_dict."""

    def __init__(self, obs_dict: dict):
        self.raw = obs_dict
        self.select = obs_dict.get('select', None)
        self.turn = obs_dict.get('turn', 1)
        self.my_side = obs_dict.get('my_side', {})
        self.opp_side = obs_dict.get('opp_side', {})
        self.phase = obs_dict.get('phase', '')
        self.first_player = obs_dict.get('first_player', None)
        self.is_first = obs_dict.get('is_first', False)

    @property
    def is_deck_selection(self) -> bool:
        return self.select is None

    @property
    def options(self) -> list:
        if self.select is None:
            return []
        return self.select.get('option', [])

    @property
    def can_attack(self) -> bool:
        # P2 can attack on turn 1; both can attack from turn 2+
        return self.turn > 1 or not self.is_first

    @property
    def my_active(self) -> Optional[dict]:
        return self.my_side.get('active')

    @property
    def opp_active(self) -> Optional[dict]:
        return self.opp_side.get('active')

    @property
    def my_bench(self) -> list:
        return self.my_side.get('bench', [])

    @property
    def my_hand(self) -> list:
        return self.my_side.get('hand', [])

    @property
    def my_energy_attached(self) -> bool:
        return self.my_side.get('energy_attached', False)


