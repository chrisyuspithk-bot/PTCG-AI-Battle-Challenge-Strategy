def _parse_damage(dmg_str: str) -> int:
    if not dmg_str or dmg_str.strip() in ('n/a', '', '0'):
        return 0
    base = re.sub(r'[×+].*', '', dmg_str).strip()
    try:
        return int(base)
    except ValueError:
        return 0


def _parse_hp(pokemon: Optional[dict]) -> int:
    if pokemon is None:
        return 0
    hp = pokemon.get('hp', 0)
    if isinstance(hp, str):
        try:
            return int(hp)
        except ValueError:
            return 0
    return hp


def _current_hp(pokemon: Optional[dict]) -> int:
    """Estimate current HP (max - damage)."""
    if pokemon is None:
        return 0
    hp = _parse_hp(pokemon)
    dmg = pokemon.get('damage', 0)
    if isinstance(dmg, str):
        try:
            dmg = int(dmg)
        except ValueError:
            dmg = 0
    return max(0, hp - dmg)


def _calculate_threat(my_active: Optional[dict], opp_active: Optional[dict]) -> dict:
    """Quick threat assessment: can I KO? Can opponent KO me?"""
    if my_active is None or opp_active is None:
        return {'i_can_ko': False, 'opp_can_ko': False}

    my_dmg = _parse_damage(my_active.get('attack_damage', '0'))
    opp_dmg = _parse_damage(opp_active.get('attack_damage', '0'))
    opp_hp = _current_hp(opp_active)
    my_hp = _current_hp(my_active)

    return {
        'i_can_ko': my_dmg >= opp_hp,
        'opp_can_ko': opp_dmg >= my_hp,
        'my_dmg': my_dmg,
        'opp_dmg': opp_dmg,
        'opp_hp': opp_hp,
        'my_hp': my_hp,
    }


def select_action(obs: GameObservation) -> list[int]:
    """
    Main action selection using threat-aware heuristic.

    Priority order:
    1. KO opponent if possible (GUARANTEED_KO)
    2. Retreat if active would die (SURVIVAL)
    3. Evolve active if possible (DEVELOP)
    4. Play basics to bench (DEVELOP)
    5. Attach energy to active (DEVELOP)
    6. Attack (FALLBACK)
    7. Pass (FALLBACK)
    """
    options = obs.options
    if not options:
        return [0]

    threat = _calculate_threat(obs.my_active, obs.opp_active)

    # Analyze each option
    best_idx = 0
    best_priority = 999

    for i, opt in enumerate(options):
        opt_type = opt.get('type', '').lower()
        priority = 100  # default low priority

        if opt_type in ('attack', 'use_attack'):
            if threat['i_can_ko']:
                priority = 0  # GUARANTEED_KO
            elif obs.can_attack and threat['my_dmg'] > 0:
                priority = 5  # ATTACK_FAVORABLE
            else:
                priority = 8  # ATTACK_ANY
        elif opt_type == 'retreat':
            if threat['opp_can_ko'] and len(obs.my_bench) > 0:
                priority = 1  # SURVIVAL_RETREAT
            else:
                priority = 7  # RETREAT_LOW_HP
        elif opt_type in ('evolve', 'evolution'):
            priority = 2  # EVOLVE
        elif opt_type in ('play_basic', 'bench', 'play_to_bench'):
            priority = 3  # PLAY_BASIC
        elif opt_type in ('attach_energy', 'energy_attach'):
            if not obs.my_energy_attached:
                priority = 4  # ATTACH_ENERGY
            else:
                priority = 9
        elif opt_type == 'pass':
            priority = 10  # PASS

        if priority < best_priority:
            best_priority = priority
            best_idx = i

    return [best_idx]


