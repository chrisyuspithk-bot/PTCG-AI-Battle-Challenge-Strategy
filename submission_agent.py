def load_card_id_map(csv_path: str = '/kaggle/input/EN_Card_Data.csv') -> dict[str, int]:
    """Map card names to their Card IDs from the official CSV."""
    name_to_id = {}
    with open(csv_path, 'r', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            name = row.get('Card Name', '').strip()
            cid_str = row.get('Card ID', row.get('card_id', '0')).strip()
            try:
                cid = int(cid_str)
            except ValueError:
                continue
            if name not in name_to_id:
                name_to_id[name] = cid
    return name_to_id


def get_deck_card_ids(name_to_id: dict[str, int]) -> list[int]:
    """Convert deck card names to card IDs."""
    ids = []
    for name in DECK_CARD_NAMES:
        cid = name_to_id.get(name)
        if cid is not None:
            ids.append(cid)
    # Pad to 60 if needed (shouldn't happen with correct card names)
    while len(ids) < 60 and ids:
        ids.append(ids[-1])
    return ids[:60]


