# Cache for deck card IDs (loaded once on first call)
_deck_ids: Optional[list[int]] = None


def agent(obs_dict: dict) -> list[int]:
    """
    Official agent entry point for Kaggle submission.

    Called repeatedly by the game engine:
    - First call: obs['select'] is None → return 60 card IDs (deck)
    - Subsequent calls: obs['select'] has options → return chosen indices
    """
    global _deck_ids

    obs = GameObservation(obs_dict)

    # Deck selection (first call only)
    if obs.is_deck_selection:
        if _deck_ids is None:
            # Load card ID mapping from the competition's data file
            name_to_id = load_card_id_map()
            _deck_ids = get_deck_card_ids(name_to_id)
        return _deck_ids

    # Action selection
    return select_action(obs)


